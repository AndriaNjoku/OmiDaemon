"""Slide presentation dispatcher generating Marp-compatible slide decks."""

import re
from datetime import datetime
from pathlib import Path
from typing import Optional
from ..models import AnalysisResult, TranscriptDocument
from ..config import SlidesConfig


class SlidesDispatcher:
    def __init__(self, config: SlidesConfig):
        self.config = config

    @staticmethod
    def sanitize_filename(name: str) -> str:
        sanitized = re.sub(r'[\\/*?:"<>|]', "", name)
        sanitized = re.sub(r"\s+", " ", sanitized).strip()
        return sanitized[:80] or "Presentation Draft"

    def dispatch(self, result: AnalysisResult, doc: TranscriptDocument) -> Optional[str]:
        """Generate presentation slides if requested by routing or slides_draft present."""
        if not self.config.enabled:
            return None
        if not result.routing.draft_slides and not result.slides_draft:
            return None

        draft = result.slides_draft
        if not draft:
            return None

        out_dir = Path(self.config.output_dir).resolve()
        out_dir.mkdir(parents=True, exist_ok=True)

        date_str = datetime.fromtimestamp(doc.modified_time).strftime("%Y-%m-%d")
        safe_title = self.sanitize_filename(draft.title or result.title)
        file_path = out_dir / f"{date_str} - {safe_title}.presentation.md"

        theme = draft.theme or self.config.theme or "gaia"

        # Format Marp markdown presentation
        sections = [
            "---",
            "marp: true",
            f"theme: {theme}",
            "_class: lead",
            "paginate: true",
            "backgroundColor: #ffffff",
            "---\n",
            f"# {draft.title}\n",
            f"**Executive Briefing & Strategy**  \n*{date_str} | Generated by OmiDaemon*\n",
        ]

        # Slide pages
        for s in draft.slides:
            slide_title = s.get("title", "Topic Overview")
            slide_content = s.get("content", "")
            sections.append(f"---\n\n## {slide_title}\n\n{slide_content}\n")

        file_path.write_text("\n".join(sections), encoding="utf-8")
        return str(file_path.resolve())
